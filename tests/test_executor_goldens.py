"""Frozen executor outputs — the acceptance instrument for engine
refactors.

A refactor that moves arithmetic between modules promises that *no
value moves*.  That promise needs an instrument, because the suite's
existing cross-engine gates cannot supply one: the torus-vs-SP-algebra
comparison gates at 1e-10 and measures 4.06e-13, the torus-vs-``graph_sample``
comparison gates at 1e-10 and measures 3.32e-15.  A genuine defect in the
shared executor would sit two to four orders *inside* those gates and
never surface.  So the values are frozen here at their exact float64
bits, and each record carries the tolerance its engine is entitled to.

The freeze set lives in ``fixtures/executor_goldens.json`` and is
regenerated by ``fixtures/_freeze_executor_goldens.py``.  Re-freezing is
a deliberate act: it resets the reference that any refactor in progress
is checked against, so it belongs in its own commit with the reason
stated.

**Bit-identity is a same-environment property, and this file does not
pretend otherwise.**  ``numpy``'s ``power``, ``cos`` and FFT reduce
differently across libm, BLAS and SIMD builds: 14 of the 41 records
differ between macOS/Accelerate and the Linux CI runner, by 1 to 8 ulp.
The pattern is *not* the BLAS-matmul one that
``tests/test_direct_sum_lazy.py`` isolates — a diagonal d = 2 lattice
and several d = 1 records diverge while the skew d = 2 record does not
— so it cannot be narrowed to a subset and excluded.  Records gated
``exact`` are therefore compared bitwise **only in the environment the
freeze was made in**, and against a calibrated 64-ulp bound elsewhere.
The consequence is stated by ``test_which_gate_this_environment_runs``
on every run: a green CI does not certify bit-identity.  Run the suite
on the freezing machine for that — which is where a refactor must be
checked.

Three properties of the freeze set are themselves asserted here, because
a golden file that cannot reach the code under test certifies nothing:

* every executor the frontend routes to appears (:class:`TestCoverage`);
* the FFT peel actually executes — at d = 1 only under a forced gate,
  since ``_conv_possible`` is False at every shipped d = 1 rung
  (:class:`TestAntiVacuity`);
* the forced-gate records really do take a different code path from
  their default-gate twins, rather than silently re-running the same
  arithmetic under a flag nothing reads.

``nu = inf`` records carry an extra, engine-independent gate: the value
counts nearest-neighbour homomorphisms, so it must be an exact integer
and the peel must not fire.  That check survives a re-freeze — a
regenerated golden could launder ``6.0 -> 5.999999999999999`` past the
bit comparison, but not past integrality.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import numpy as np
import pytest

import gzl.direct_sum as ds
import gzl.tensor_network as tn

_FIXTURES = Path(__file__).parent / "fixtures"
_GOLDEN_PATH = _FIXTURES / "executor_goldens.json"


def _load_freezer():
    """Import the regeneration script as a module (it is not a package)."""
    spec = importlib.util.spec_from_file_location(
        "_freeze_executor_goldens", _FIXTURES / "_freeze_executor_goldens.py",
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


_freezer = _load_freezer()
_PAYLOAD = json.loads(_GOLDEN_PATH.read_text())
RECORDS = _PAYLOAD["records"]
BY_LABEL = {r["label"]: r for r in RECORDS}

# --- which gate this environment is entitled to run ------------------------
#
# Bit-identity is a property of the environment, not of this library.
# numpy's power, cos and FFT reduce differently across libm, BLAS and
# SIMD builds: 14 of these 41 records differ between macOS/Accelerate
# and the Linux CI runner, by 1 to 8 ulp.  The pattern is not the
# BLAS-matmul one that tests/test_direct_sum_lazy.py isolates — a
# *diagonal* d = 2 lattice and several d = 1 records diverge, while the
# skew d = 2 record does not — so it cannot be narrowed to a subset of
# records and excluded.
#
# The cross-environment bound is therefore CALIBRATED, not chosen.
# Measured, over this record set:
#
#     cross-platform noise            1 -  8 ulp
#     _USE_CONV off (torus)                848 ulp   <- smallest real defect
#     torus mixed orientation            1.4e11 ulp
#     hybrid orientation fix off         8.3e11 ulp
#     marker rule / box kill switch      5.7e15 ulp
#
# 64 ulp sits 8x above the noise and 13x below the smallest real defect.
# What it gives up is stated plainly rather than hidden: a pure
# reassociation moves 3 ulp (reversed dense factor order) to 6 ulp (a
# 1-ulp kernel exponent), so those are invisible to the portable gate —
# they are the same size as the platform noise, and no cross-platform
# comparison can separate them.  They ARE caught on the freezing
# machine, which is where a refactor must be checked.
CROSS_ENV_ULP = 64.0
_FROZEN_ON = _PAYLOAD.get("fingerprint", {})
SAME_ENV = _FROZEN_ON == _freezer.fingerprint()

# Handle on this module, so the two gate branches can each be forced and
# exercised regardless of which environment the suite happens to run in.
_mod = sys.modules[__name__]

# Executors the frontend can reach.  Anything routable and absent here is
# an unfrozen engine, which is the gap this file exists to close.
ROUTABLE = {
    "direct_sum_zero_momentum",
    "_direct_sum_open_terminal",
    "direct_sum_extrapolated",
    "_direct_sum_extrapolated_grid",
    "graph_zeta_general",
    "graph_zeta_general_at_zero",
    "hybrid_zeta",
}


