def _deviation(got, want):
    """Return ``(bit_identical, max_rel, max_ulp)`` for a value pair.

    ``max_rel`` is scaled by the largest golden magnitude rather than
    elementwise, so a near-zero entry cannot manufacture a huge ratio out
    of a last-bit difference.  ``max_ulp`` stays elementwise, since that
    is the quantity the cross-environment ulp bound is written in.
    """
    got = np.asarray(got)
    want = np.asarray(want)
    assert got.shape == want.shape, f"shape moved: {got.shape} vs {want.shape}"
    identical = np.array_equal(got, want)
    diff = np.abs(got - want)
    scale = np.max(np.abs(want)) if want.size else 0.0
    max_rel = float(np.max(diff) / scale) if scale > 0 else float(np.max(diff))
    spacing = np.spacing(np.abs(np.asarray(want, dtype=np.complex128).real))
    spacing = np.maximum(spacing, np.finfo(float).tiny)
    max_ulp = float(np.max(diff / spacing))
    return identical, max_rel, max_ulp


def _check(rec, got):
    want = _freezer._decode(rec["value"])
    identical, max_rel, max_ulp = _deviation(got, want)
    tol = rec["tol"]
    if tol["kind"] == "exact":
        if _mod.SAME_ENV:
            assert identical, (
                f"{rec['label']}: value moved off its frozen bits "
                f"(max_rel={max_rel:.3e}, max_ulp={max_ulp:.1f}). This "
                f"engine is gated bit-identical in the environment the "
                f"freeze was made in; a tolerance here would hide exactly "
                f"the class of defect the freeze exists to catch."
            )
        else:
            assert max_ulp <= CROSS_ENV_ULP, (
                f"{rec['label']}: max_ulp={max_ulp:.1f} > {CROSS_ENV_ULP} "
                f"across environments (frozen on {_FROZEN_ON}, running on "
                f"{_freezer.fingerprint()}). Platform noise measured 1-8 "
                f"ulp and the smallest real defect 848 ulp, so this is "
                f"far outside round-off — treat it as a defect, not as a "
                f"tolerance to widen."
            )
    elif tol["kind"] == "relative":
        assert max_rel <= tol["rtol"], (
            f"{rec['label']}: max_rel={max_rel:.3e} > {tol['rtol']:.1e}"
        )
    elif tol["kind"] == "ulp":
        assert max_ulp <= tol["n_ulp"], (
            f"{rec['label']}: max_ulp={max_ulp:.1f} > {tol['n_ulp']}"
        )
    else:                                        # pragma: no cover
        raise AssertionError(f"unknown tolerance kind {tol['kind']!r}")
    return max_rel, max_ulp


